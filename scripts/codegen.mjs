#!/usr/bin/env node
// Generates packages/client/src/generated/schema.d.ts from the OpenAPI contract.
// Usage: node scripts/codegen.mjs [spec-path] [--check]
// Env: OPENAPI_PATH overrides the spec path; CODEGEN_REQUIRE_SPEC=1 makes --check fail when spec is missing.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const argPath = args.find((a) => !a.startsWith("--"));
const specPath = resolve(argPath || process.env.OPENAPI_PATH || resolve(root, "../saas_core/openapi/v1.yaml"));
const outPath = resolve(root, "packages/client/src/generated/schema.d.ts");

if (!existsSync(specPath)) {
  const msg = `codegen: contract not present at ${specPath}, skipping`;
  if (check && process.env.CODEGEN_REQUIRE_SPEC === "1") {
    console.error(msg + " (CODEGEN_REQUIRE_SPEC=1)");
    process.exit(1);
  }
  console.log(msg);
  process.exit(0);
}

const ast = await openapiTS(pathToFileURL(specPath));
const generated = astToString(ast);
const header = "// Generated by scripts/codegen.mjs from the OpenAPI contract. Do not edit.\n";
const content = header + generated;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
  if (current !== content) {
    console.error(
      `codegen:check FAILED: ${outPath} is ${current === null ? "missing" : "out of date"} vs ${specPath}.\nRun \`pnpm codegen\` and commit the result.`
    );
    process.exit(1);
  }
  console.log("codegen:check OK: generated client types match the contract");
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, content);
  console.log(`codegen: wrote ${outPath} from ${specPath}`);
}
